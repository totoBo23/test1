function validateStep(step) {
  const current = stepElements.find((el) => Number(el.dataset.step) === step);

  if (!current) {
    return true;
  }

  let firstInvalid = null;

  current.querySelectorAll("input, select").forEach((field) => {
    field.removeAttribute("aria-invalid");

    if (!field.checkValidity()) {
      field.setAttribute("aria-invalid", "true");
      if (!firstInvalid) {
        firstInvalid = field;
      }
    }
  });

  if (firstInvalid) {
    firstInvalid.reportValidity();
    return false;
  }

  if (step === 1) {
    if (manualAddressMode) {
      let firstManualInvalid = null;
      [manualAddress.street, manualAddress.houseNumber, manualAddress.postalCode, manualAddress.city, manualAddress.state].forEach((field) => {
        field.removeAttribute("aria-invalid");
        field.setCustomValidity("");
        if (!field.value.trim()) {
          field.setAttribute("aria-invalid", "true");
          field.setCustomValidity(t("addressIncompleteError"));
          if (!firstManualInvalid) {
            firstManualInvalid = field;
          }
        }
      });

      if (firstManualInvalid) {
        firstManualInvalid.reportValidity();
        return false;
      }

      if (!applyManualAddressToHidden()) {
        return false;
      }
    } else {
      const searchField = addressFields.search;
      searchField.setCustomValidity("");

      if (!addressSelectedFromSuggestion || !addressFields.state.value) {
        if (usingNewPlaceAutocomplete) {
          setAddressStatus("addressSelectSuggestionError");
        } else {
          searchField.setAttribute("aria-invalid", "true");
          searchField.setCustomValidity(t("addressSelectSuggestionError"));
          searchField.reportValidity();
        }
        return false;
      }
    }
  }

  if (step === 3 && Number(numberFields.size.value) <= 0) {
    numberFields.size.setAttribute("aria-invalid", "true");
    numberFields.size.focus();
    return false;
  }

  if (step === 3 && Number(numberFields.netRent.value) <= 0) {
    numberFields.netRent.setAttribute("aria-invalid", "true");
    numberFields.netRent.focus();
    return false;
  }

  if (step === 3) {
    const startDate = parseLocalDate(contractFields.start.value);
    const endDate = parseLocalDate(contractFields.end.value);
    const today = getTodayAtMidnight();

    contractFields.start.setCustomValidity("");
    contractFields.end.setCustomValidity("");

    if (startDate && startDate > today) {
      contractFields.start.setAttribute("aria-invalid", "true");
      contractFields.start.setCustomValidity(t("contractDateFutureError"));
      contractFields.start.reportValidity();
      return false;
    }

    if (!contractFields.stillRunning.checked && !contractFields.end.value) {
      contractFields.end.setAttribute("aria-invalid", "true");
      contractFields.end.setCustomValidity(t("contractEndRequiredError"));
      contractFields.end.reportValidity();
      return false;
    }

    if (!contractFields.stillRunning.checked && startDate && endDate && endDate < startDate) {
      contractFields.end.setAttribute("aria-invalid", "true");
      contractFields.end.setCustomValidity(t("contractDateOrderError"));
      contractFields.end.reportValidity();
      return false;
    }
  }

  return true;
}

