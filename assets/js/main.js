function calculateResult() {
  const data = new FormData(form);
  const state = data.get("state");
  const size = Number(data.get("apartment_size_m2")) || 0;
  const currentRent = Number(data.get("monthly_rent_net")) || 0;
  const buildingAge = data.get("building_age") || "unknown";
  const contractStartDate = parseLocalDate(data.get("contract_start_date"));
  const contractEndInput = parseLocalDate(data.get("contract_end_date"));
  const contractStillRunning = contractFields.stillRunning.checked;
  const contractEndDate = contractStillRunning || !contractEndInput ? getTodayAtMidnight() : contractEndInput;
  const contractMonths = contractStartDate ? calculateContractMonths(contractStartDate, contractEndDate) : 1;

  const base = richtwertByState[state] || 0;

  const totalAdjustments =
    (adjustments.floor_level[data.get("floor_level")] || 0) +
    (adjustments.elevator[data.get("elevator")] || 0) +
    (adjustments.balcony[data.get("balcony")] || 0) +
    (adjustments.condition[data.get("condition")] || 0) +
    (adjustments.equipment[data.get("equipment")] || 0) +
    (adjustments.location_quality[data.get("location_quality")] || 0);

  const legalRentM2 = Math.max(base + totalAdjustments, 0);
  const legalRentTotal = legalRentM2 * size;
  const overpayment = Math.max(currentRent - legalRentTotal, 0);
  const refund = overpayment * contractMonths;

  const ratio = currentRent > 0 ? overpayment / currentRent : 0;

  let riskLevel = "low";
  if (buildingAge !== "after_2021") {
    if (overpayment > 250 || ratio >= 0.2) {
      riskLevel = "high";
    } else if (overpayment > 0) {
      riskLevel = "medium";
    }
  }

  const qualified = riskLevel !== "low";

  lastResult = {
    legalRentM2,
    legalRentTotal,
    currentRent,
    overpayment,
    contractMonths,
    refund,
    buildingAge,
    riskLevel,
    qualified
  };

  return lastResult;
}

function renderResult(result) {
  resultFields.legalM2.textContent = `${formatCurrency(result.legalRentM2)} ${t("resultPerSquareMeter")}`;
  resultFields.legalTotal.textContent = formatCurrency(result.legalRentTotal);
  resultFields.currentRent.textContent = formatCurrency(result.currentRent);
  resultFields.overpayment.textContent = formatCurrency(result.overpayment);
  resultFields.durationMonths.textContent = `${result.contractMonths} ${t("resultDurationUnit")}`;
  resultFields.refund.textContent = formatCurrency(result.refund);

  const summaryParts = [];
  if (result.buildingAge === "after_2021") {
    summaryParts.push(t("summaryAfter2021"));
  }
  if (result.riskLevel === "high") {
    summaryParts.push(t("summaryHigh"));
  } else if (result.riskLevel === "medium") {
    summaryParts.push(t("summaryMedium"));
  } else {
    summaryParts.push(t("summaryLow"));
  }
  summaryParts.push(t("summaryContractDuration").replace("{months}", String(result.contractMonths)));

  resultFields.summary.textContent = summaryParts.join(" ");

  qualifiedBox.hidden = !result.qualified;
  notQualifiedBox.hidden = result.qualified;
  leadFeedback.textContent = "";

  [leadFields.name, leadFields.email, leadFields.phone, leadFields.consent].forEach((field) => {
    field.removeAttribute("aria-invalid");
  });
}

function validateLead() {
  if (!lastResult || !lastResult.qualified) {
    return false;
  }

  let firstInvalid = null;

  [leadFields.name, leadFields.email, leadFields.phone].forEach((field) => {
    field.removeAttribute("aria-invalid");
    if (!field.value.trim() || !field.checkValidity()) {
      field.setAttribute("aria-invalid", "true");
      if (!firstInvalid) {
        firstInvalid = field;
      }
    }
  });

  leadFields.consent.removeAttribute("aria-invalid");
  if (!leadFields.consent.checked) {
    leadFields.consent.setAttribute("aria-invalid", "true");
    if (!firstInvalid) {
      firstInvalid = leadFields.consent;
    }
  }

  if (firstInvalid) {
    firstInvalid.reportValidity();
    return false;
  }

  return true;
}

